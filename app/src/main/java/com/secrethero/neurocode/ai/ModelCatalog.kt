/**
 * Семейство модели — подпись и вендор на карточке каталога.
 */
enum class ModelFamily(val label: String, val vendor: String) {
    QWEN("Qwen", "Alibaba"),
    GEMMA("Gemma", "Google"),
    LLAMA("Llama", "Meta"),
    PHI("Phi", "Microsoft"),
    SMOL_LM("SmolLM", "Hugging Face"),
    DEEPSEEK("DeepSeek", "DeepSeek"),
    VIKHR("Vikhr", "Vikhr-Nemo"),
}

/**
 * Формат диалога, который модель понимает. Хранится в описании модели, а не угадывается
 * по имени файла: для импортированных вручную GGUF шаблон выбирается пользователем.
 */
enum class ChatTemplate {
    CHATML,
    QWEN3,
    LLAMA3,
    GEMMA,
    PHI3,
    DEEPSEEK_R1,
}

/**
 * Описание локальной модели из каталога. [id] — стабильный ключ, по нему хранится
 * скачанный файл (`<id>.gguf`), поэтому при смене URL или имени id не меняется.
 */
data class ModelSpec(
    val id: String,
    val name: String,
    val description: String,
    val url: String,
    val sizeMb: Long,
    val family: ModelFamily,
    val parameters: String,
    val minRamGb: Int,
    val quality: Int,
    val speed: Int,
    val russian: Int,
    val license: String,
    val tags: List<String> = emptyList(),
    val recommended: Boolean = false,
    val defaultContext: Int = 8192,
    val defaultGpuLayers: Int = 0,
    val chatTemplate: ChatTemplate = ChatTemplate.CHATML,
    val gated: Boolean = false,
) {
    /** Размер файла в байтах (для сравнения с рекомендацией по памяти устройства). */
    val sizeBytes: Long get() = sizeMb * DeviceProfile.MB

    /** Скачиваемый файл в `files/models`: стабильный id + расширение. */
    val fileName: String get() = "$id.gguf"
}

